// Downloads the Halloween illustrations from Microsoft Fluent Emoji (MIT, "Flat" style) and writes them
// as SVG strings to components/halloween/art-data.ts, with the licence beside it. Inlined as strings so
// react-native-svg's SvgXml draws them the same on web and Android, without an SVG bundler transformer.
// Run: node scripts/fetch-halloween-art.mjs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Pinned to a commit so a re-run can't silently change the art.
const COMMIT = process.env.FLUENT_COMMIT ?? '1ffb34c752ecf5d402f04cfb4b392c77f57c54bc';
const BASE = `https://raw.githubusercontent.com/microsoft/fluentui-emoji/${COMMIT}`;
const ART = {
  ghost: 'Ghost/Flat/ghost_flat.svg',
  pumpkin: 'Jack-o-lantern/Flat/jack-o-lantern_flat.svg',
  bat: 'Bat/Flat/bat_flat.svg',
  headstone: 'Headstone/Flat/headstone_flat.svg',
  moon: 'Full moon/Flat/full_moon_flat.svg',
  candle: 'Candle/Flat/candle_flat.svg',
  crystalBall: 'Crystal ball/Flat/crystal_ball_flat.svg',
};

const dir = new URL('../components/halloween/', import.meta.url);

async function get(path) {
  const res = await fetch(`${BASE}/${path.split('/').map(encodeURIComponent).join('/')}`, { signal: AbortSignal.timeout(15000) });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.text();
}

const entries = [];
for (const [name, path] of Object.entries(ART)) {
  const svg = (await get(`assets/${path}`)).replace(/\s*\n\s*/g, ' ').trim();
  if (!svg.startsWith('<svg')) throw new Error(`${path}: not an SVG`);
  entries.push(`  ${name}: ${JSON.stringify(svg)},`);
}

const out = `// Generated by scripts/fetch-halloween-art.mjs from Microsoft Fluent Emoji (MIT, see LICENSE-fluent-emoji.txt).
// Do not edit by hand; re-run the script instead.
export const ART_XML = {
${entries.join('\n')}
} as const;

export type ArtName = keyof typeof ART_XML;
`;
await writeFile(new URL('art-data.ts', dir), out);
await writeFile(new URL('LICENSE-fluent-emoji.txt', dir), await get('LICENSE'));
console.log(`Wrote ${entries.length} illustrations to ${fileURLToPath(dir)}`);
