def grid_path(rows):
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == '#':
                start = x
                while x < len(row) and row[x] == '#':
                    x += 1
                parts.append(f'M{start * 2} {y * 2}h{(x - start) * 2}v2h-{(x - start) * 2}z')
            else:
                x += 1
    return ''.join(parts)


def svg_path(name):
    s = open(f'{SVG}/{name}.svg').read()
    return ''.join(re.findall(r'\sd="([^"]+)"', s))


def main():
    out = ['// Generated by scripts/make-pixel-icons.py. Pixelarticons paths are MIT (c) 2019 Gerrit Halfmann.',
           '/** Pixel-art path data on a 24 px grid, keyed by the Lucide icon name it replaces. */',
           'export const PIXEL_ICONS: Record<string, string> = {']
    for k, v in sorted(MAP.items()):
        out.append(f"  {k}: '{svg_path(v)}',")
    for k, v in sorted(CUSTOM.items()):
        out.append(f"  {k}: '{grid_path(v)}',")
    out.append('};')
    open('components/ui/pixel-icons.ts', 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
